void main(){
  int age = 50;
  age = 70 ; // we can change the value of variable 'age' because it is a normal variable
  print(age);


//final
final int age1 = 60; //when a variable declared as final.it can be assigned only once and cannot be change later
print(age1); //it will assign in the memory when the program is running and it will be assigned only once and cannot be change later
//const 
const double pi  = 3.14162; //when we declared a variable as constant it can be assigned only once and cannot be change later and it will be assigned in the memory when the program is compiled
print(pi); //it will assign in the memory when the program is compiled and it will be assigned only once and cannot be change later

}